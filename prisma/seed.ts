// Helper to generate a realistic cryptographic certificate
function makeCertificateData(book: {
  title: string;
  author: string;
  year: number;
  editionPrinting: string;
  slug: string;
}) {
  const certSuffix = Math.floor(1000 + Math.random() * 9000);
  const certNum = `CERT-${book.year}-${book.slug.toUpperCase().slice(0, 6)}-${certSuffix}`;
  const verificationCode = crypto.randomBytes(12).toString("hex");
  const payload = `${book.title}|${book.author}|${book.year}|${book.editionPrinting}|Julian Vance ABAA`;
  const signatureSha256 = crypto.createHash("sha256").update(payload).digest("hex");

  return {
    certificateNumber: certNum,
    verificationCode,
    signatureSha256,
    examinerName: "Julian Vance, ABAA / ILAB Appraiser",
    examinerTitle: "Senior Specialist in Antiquarian Literature & Manuscripts",
    metadataJson: JSON.stringify({
      paperStock: "Handmade rag paper, laid watermarked",
      bindingType: "Contemporary morocco with gilt armorial tooling",
      microscopicInkAnalysis: "Iron gall ink consistency verified, genuine author signature",
      catalogDate: new Date().toISOString(),
    }),
  };
}

